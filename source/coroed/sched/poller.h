#pragma once

#include <stdint.h>

struct task;

/**
 * Поллер ввода-вывода на основе epoll.
 *
 * Один экземпляр epoll на весь планировщик. Задача, которой
 * нужно дождаться готовности дескриптора, регистрирует его
 * с флагом EPOLLONESHOT и указателем на себя в `data.ptr`,
 * после чего паркуется. Рабочие потоки опрашивают epoll
 * из цикла планировщика и будят задачи готовых дескрипторов.
 */

/**
 * Создать экземпляр epoll. Вызывается из `sched_init`.
 */
void poller_init();

/**
 * Закрыть экземпляр epoll. Вызывается из `sched_destroy`.
 */
void poller_destroy();

/**
 * Находясь в задаче `caller`, дождаться, пока на `fd` станет
 * возможно `events` (EPOLLIN / EPOLLOUT). Задача паркуется
 * и продолжится после того, как поллер ее разбудит.
 *
 * Возвращает 0 или `-errno`, если зарегистрировать
 * дескриптор не удалось (тогда задача не паркуется).
 *
 * Ограничение: одновременно ждать один `fd` может
 * только одна задача.
 */
int poller_wait(struct task* caller, int fd, uint32_t events);

/**
 * Опросить epoll и разбудить задачи, чьи дескрипторы готовы.
 * Вызывается только из контекста планировщика, когда рабочий
 * поток не держит лок ни одной задачи.
 *
 * `timeout_ms`: 0 -- не ждать, иначе ждать событий не дольше
 * указанного времени. Возвращает количество разбуженных задач.
 */
int poller_poll(int timeout_ms);
