#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <sys/types.h>

/**
 * Минимальная обработка HTTP/1.x без ввода-вывода.
 *
 * Модуль общий для сервера на корутинах и сервера на потоках:
 * они отличаются только тем, как читают и пишут байты.
 */

enum {
  /**
   * Максимальный размер заголовков запроса. Запрос длиннее
   * получает 431 и соединение закрывается.
   */
  HTTP_MAX_REQUEST_SIZE = 8 * 1024,

  /**
   * Буфера такого размера достаточно для любого ответа:
   * имя ограничено размером запроса и после экранирования
   * в JSON растет не более чем в 6 раз.
   */
  HTTP_MAX_RESPONSE_SIZE = 6 * HTTP_MAX_REQUEST_SIZE + 512,
};

/**
 * Найти конец заголовков запроса (`\r\n\r\n`) в `buf`.
 * Возвращает длину запроса вместе с разделителем
 * или -1, если запрос пришел еще не полностью.
 */
ssize_t http_request_length(const char* buf, size_t len);

/**
 * Обработать один запрос `request` длины `request_len`
 * (заголовки целиком) и записать ответ в `response`
 * (размер не меньше HTTP_MAX_RESPONSE_SIZE).
 *
 * Маршруты:
 *   GET /hello/<name>  -> 200 {"message":"<name>"}
 *   другой путь        -> 404
 *   другой метод       -> 405
 *   некорректный запрос -> 400
 *
 * `keep_alive` -- можно ли читать следующий запрос из того
 * же соединения (HTTP/1.1 по умолчанию да, HTTP/1.0 -- нет).
 *
 * Возвращает длину ответа.
 */
size_t http_handle(const char* request, size_t request_len, char* response, bool* keep_alive);

/**
 * Ответ на слишком длинный запрос (431), после него
 * соединение закрывается. Возвращает длину ответа.
 */
size_t http_too_large(char* response);
